                        )

                        FilterChip(
                            selected = selectedRole == "midwife",
                            onClick = { selectedRole = "midwife" },
                            label = { Text("Midwife / LMC") },
                            leadingIcon = {
                                Icon(
                                    imageVector = Icons.Default.MedicalServices,
                                    contentDescription = null,
                                    modifier = Modifier.size(18.dp)
