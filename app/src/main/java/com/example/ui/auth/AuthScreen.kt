                            },
                            colors = FilterChipDefaults.filterChipColors(
                                selectedContainerColor = MaterialTheme.colorScheme.primaryContainer,
                                selectedLabelColor = MaterialTheme.colorScheme.onPrimaryContainer
                            ),
                            modifier = Modifier.testTag("role_midwife_chip")
                        )
                    }

                    Spacer(modifier = Modifier.height(12.dp))

                    Text(
                        text = if (selectedRole == "parent")
                            "Log feeding, sleep, and diapers. Real-time sync between partners & secure link with your Midwife."
                        else
                            "Clinical dashboard to monitor client babies, schedule visits, and message parents directly.",
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
